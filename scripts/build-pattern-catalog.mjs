const body = JSON.stringify(patterns, null, 2);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${header}${body};\n`, 'utf8');

const byCategory = {};
for (const p of patterns) byCategory[p.category] = (byCategory[p.category] ?? 0) + 1;
console.log(`[build-pattern-catalog] wrote ${patterns.length} patterns → ${out}`);
console.log('[build-pattern-catalog] by category:', JSON.stringify(byCategory, null, 2));
